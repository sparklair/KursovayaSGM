import numpy as np

# Матрица коэффициентов левой части
A = np.array([
    [13.819, 9],      # первое уравнение: 13.819a + 9b = -0.016
    [28.603, 13.819]  # второе уравнение: 28.603a + 13.819b = -21.150
])

# Вектор правой части
B = np.array([-0.016, -21.150])

solution = np.linalg.solve(A, B)
a, b = solution

print(f"a = {a:.6f}")
print(f"b = {b:.6f}")
