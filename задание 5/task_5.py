import numpy as np

# коэффициенты системы
P = np.array([
    [0.12, -0.23, 0.25, -0.16],
    [0.14, 0.34, -0.18, 0.24],
    [0.33, 0.03, 0.16, -0.32],
    [0.12, -0.05, 0.00, 0.15]
])

# свободные члены
F = np.array([1.24, -0.89, 1.15, -0.57])

# Проверка условия сходимости
norm_P = np.max(np.sum(np.abs(P), axis=1))
print(f'1) Проверка условия сходимости: Норма матрицы P = {norm_P:.4f}.')
if norm_P < 1:
    print(f'   Так как {norm_P:.4f} < 1, достаточное условие сходимости выполнено.')
    print('   Метод итераций сходится.\n')
else:
    print('   Условие сходимости не выполнено.\n')

# Итерации
iterations = 4  # по решению преподавателя
x = np.zeros(4)  # начальное приближение (0, 0, 0, 0)
results = [np.concatenate(([0], x))]  # [итерация, x1, x2, x3, x4]

print('2) Выполнение итераций. Начальное приближение: (0, 0, 0, 0).\n')

for k in range(1, iterations + 1):
    x = P @ x + F
    results.append(np.concatenate(([k], x)))

# Оценка погрешности 4-й итерации
x_prev = results[-2][1:]
x_curr = results[-1][1:]
norm_diff = np.sum(np.abs(x_curr - x_prev))
error_est = (norm_P / (1 - norm_P)) * norm_diff

# Вывод таблицы
print('Таблица итераций:')
print('+' + '-'*12 + '+' + '-'*14 + '+' + '-'*14 + '+' + '-'*14 + '+' + '-'*14 + '+')
print(f'| {'Итерация':^10} | {'x1':^12} | {'x2':^12} | {'x3':^12} | {'x4':^12} |')
print('+' + '-'*12 + '+' + '-'*14 + '+' + '-'*14 + '+' + '-'*14 + '+' + '-'*14 + '+')

for row in results:
    print(f'| {int(row[0]):^10} | {row[1]:^12.5f} | {row[2]:^12.5f} | {row[3]:^12.5f} | {row[4]:^12.5f} |')
print('+' + '-'*12 + '+' + '-'*14 + '+' + '-'*14 + '+' + '-'*14 + '+' + '-'*14 + '+')

print('\nВыводы:')
print(f'3) Теоретическая оценка погрешности 4-й итерации:')
print(f'   Норма матрицы P: ||P|| = {norm_P:.4f}')
print(f'   Норма разности между 4-й и 3-й итерациями (L1): ||X(4) - X(3)|| = {norm_diff:.6f}')
print(f'   Погрешность: ||X* - X(4)|| <= {error_est:.6f}\n')
print(f'Ответ: После 4 итераций приближённое решение системы:')
print(f'   x1 = {results[-1][1]:.5f}')
print(f'   x2 = {results[-1][2]:.5f}')
print(f'   x3 = {results[-1][3]:.5f}')
print(f'   x4 = {results[-1][4]:.5f}')
